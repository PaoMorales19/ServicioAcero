package dto;

public class Devolution {

	public String idDevolucion;
	public String idCompra;
	public String razon;
	public String fechaEntrega;
	public String estadoDevolucion;
	/**
	 * @return the idDevolucion
	 */
	public String getIdDevolucion() {
		return idDevolucion;
	}
	/**
	 * @param idDevolucion the idDevolucion to set
	 */
	public void setIdDevolucion(String idDevolucion) {
		this.idDevolucion = idDevolucion;
	}
	/**
	 * @return the idCompra
	 */
	public String getIdCompra() {
		return idCompra;
	}
	/**
	 * @param idCompra the idCompra to set
	 */
	public void setIdCompra(String idCompra) {
		this.idCompra = idCompra;
	}
	/**
	 * @return the razon
	 */
	public String getRazon() {
		return razon;
	}
	/**
	 * @param razon the razon to set
	 */
	public void setRazon(String razon) {
		this.razon = razon;
	}
	/**
	 * @return the fechaEntrega
	 */
	public String getFechaEntrega() {
		return fechaEntrega;
	}
	/**
	 * @param fechaEntrega the fechaEntrega to set
	 */
	public void setFechaEntrega(String fechaEntrega) {
		this.fechaEntrega = fechaEntrega;
	}
	/**
	 * @return the estadoDevolucion
	 */
	public String getEstadoDevolucion() {
		return estadoDevolucion;
	}
	/**
	 * @param estadoDevolucion the estadoDevolucion to set
	 */
	public void setEstadoDevolucion(String estadoDevolucion) {
		this.estadoDevolucion = estadoDevolucion;
	}

}
